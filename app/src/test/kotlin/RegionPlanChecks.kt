import com.example.simregionswitcher.RegionPlan
import com.example.simregionswitcher.RegionGuard

fun regionPlanChecks(): Int {
    var total = 0
    fun expect(value: Boolean) { check(value); total++ }
    val a1 = RegionPlan(0, 3, "A1 BY", "257", "01", false, "222", "88")
    val orange = RegionPlan(1, 2, "Orange", "260", "03", true, "222", "88")
    expect(a1.valid()); expect(orange.valid())
    expect(a1.matches(0, 3, "257", "01", false))
    expect(orange.matches(1, 2, "260", "03", true))
    expect(!a1.matches(1, 2, "260", "03", true))
    expect(!a1.matches(0, 9, "257", "01", false))
    expect(!orange.matches(1, 2, "260", "03", false))
    expect(!a1.matches(0, 3, "222", "88", false))
    expect(!a1.matches(0, 3, null, "01", false))
    expect(!a1.copy(subId = -1).valid())
    expect(!a1.copy(slot = -1).valid()); expect(!a1.copy(slot = 2).valid())
    for (mcc in listOf("22", "2222", "22a", " 222", "２２２")) expect(!a1.copy(mcc = mcc).valid())
    for (mnc in listOf("8", "8888", " 88", "٨٨")) expect(!a1.copy(mnc = mnc).valid())
    expect(a1.copy(mnc = "01").valid()); expect(a1.copy(mnc = "001").valid())
    expect(!a1.copy(sourceMcc = "").valid()); expect(!a1.copy(sourceMnc = "1").valid())
    expect(!a1.copy(operator = "a".repeat(101)).valid())
    expect(RegionGuard.canApply(a1, a1, true, false, false))
    expect(!RegionGuard.canApply(a1, orange, true, false, false))
    expect(!RegionGuard.canApply(a1, a1.copy(mnc = "89"), true, false, false))
    expect(!RegionGuard.canApply(a1, a1.copy(subId = 9), true, false, false))
    expect(!RegionGuard.canApply(a1, null, true, false, false))
    expect(!RegionGuard.canApply(null, a1, true, false, false))
    expect(!RegionGuard.canApply(a1, a1, false, false, false))
    expect(!RegionGuard.canApply(a1, a1, true, true, false))
    expect(!RegionGuard.canApply(a1, a1, true, false, true))
    expect(RegionGuard.canPrepare(false, false, "", "NOT_STARTED"))
    expect(RegionGuard.canPrepare(true, false, "apply", "MODIFIER_REPORTED_SUCCESS"))
    expect(RegionGuard.canPrepare(true, false, "apply", "MODIFIER_REPORTED_FAILURE"))
    expect(!RegionGuard.canPrepare(true, true, "apply", "MODIFIER_REPORTED_SUCCESS"))
    expect(!RegionGuard.canPrepare(true, false, "apply", "OUTCOME_UNCERTAIN"))
    expect(!RegionGuard.canPrepare(true, true, "prepare", "PENDING_UNKNOWN"))
    expect(!RegionGuard.canPrepare(true, false, "prepare", "MODIFIER_REPORTED_SUCCESS"))
    expect(!RegionGuard.canPrepare(true, false, "apply", "UNKNOWN"))
    val reset = a1.copy(mcc = a1.sourceMcc, mnc = a1.sourceMnc, reset = true)
    expect(reset.valid())
    expect(!a1.copy(reset = true).valid())
    expect(!reset.copy(mnc = "001").valid())
    expect(reset.matches(0, 3, "257", "01", false))
    expect(!reset.matches(1, 2, "260", "03", true))
    expect(!RegionGuard.canApply(reset, reset.copy(reset = false), true, false, false))
    expect(!RegionGuard.canApply(reset.copy(reset = false), reset, true, false, false))
    expect(RegionGuard.canApply(reset, reset, true, false, false))
    expect(!RegionGuard.canApply(reset, reset, true, true, false))
    expect(!RegionGuard.canApply(reset, reset, true, false, true))
    expect(!RegionGuard.canApply(reset, reset, false, false, false))
    val args = com.example.simregionswitcher.RegionActionRules.modifierArguments(reset)
    expect(args.keys == setOf("select_sim_id", "reset"))
    expect(args["select_sim_id"] == 3 && args["select_sim_id"] is Int)
    expect(args["reset"] == true && args["reset"] is Boolean)
    val second = orange.copy(mcc = orange.sourceMcc, mnc = orange.sourceMnc, reset = true)
    expect(com.example.simregionswitcher.RegionActionRules.modifierArguments(second)["select_sim_id"] == 2)
    val normal = com.example.simregionswitcher.RegionActionRules.modifierArguments(a1)
    expect(normal.keys == setOf("select_sim_id", "country_mcc_override", "country_mnc_hint"))
    expect(normal["country_mcc_override"] == "222" && normal["country_mnc_hint"] == "88")
    expect(com.example.simregionswitcher.RegionActionRules.modifierArguments(a1.copy(mcc = "260", mnc = "01"))["country_mnc_hint"] == "01")
    expect(runCatching { com.example.simregionswitcher.RegionActionRules.modifierArguments(reset.copy(subId = -1)) }.isFailure)
    expect(runCatching { com.example.simregionswitcher.RegionActionRules.modifierArguments(a1.copy(reset = true)) }.isFailure)
    return total
}
